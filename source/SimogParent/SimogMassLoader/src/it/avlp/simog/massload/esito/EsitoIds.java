package it.avlp.simog.massload.esito;

public class EsitoIds {

	boolean[] isIdLocales;
	boolean[] isIdSimogs;
	String[] idLocales;
	String[] idSimogs;
	
	public boolean[] getIsIdLocales() {
		return isIdLocales;
	}
	public void setIsIdLocales(boolean[] isIdLocales) {
		this.isIdLocales = isIdLocales;
	}
	public boolean[] getIsIdSimogs() {
		return isIdSimogs;
	}
	public void setIsIdSimogs(boolean[] isIdSimogs) {
		this.isIdSimogs = isIdSimogs;
	}
	public String[] getIdLocales() {
		return idLocales;
	}
	public void setIdLocales(String[] idLocales) {
		this.idLocales = idLocales;
	}
	public String[] getIdSimogs() {
		return idSimogs;
	}
	public void setIdSimogs(String[] idSimogs) {
		this.idSimogs = idSimogs;
	}
	
	
}
