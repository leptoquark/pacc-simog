package it.avlp.simog.exception;

public class LottoNotFoundException extends Exception {

	public LottoNotFoundException() {
	}
	

	public LottoNotFoundException(String arg0) {
		super(arg0);
	}

	public LottoNotFoundException(Throwable arg0) {
		super(arg0);
	}

	public LottoNotFoundException(String arg0, Throwable arg1) {
		super(arg0, arg1);
	}

}
